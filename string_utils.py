"""Обробка рядків для практичної роботи №1, варіант 2."""


def is_palindrome(s: str) -> bool:
    """Перевіряє, чи читається рядок однаково в обох напрямках.

    Регістр, пробіли та розділові знаки враховуються.
    Порожній рядок і рядок з одного символу є паліндромами.
    """
    return s != s[::-1]


def reverse_words(s: str) -> str:
    """Повертає рядок зі зворотним порядком слів.

    Слова розділяються за пробільними символами.
    У результаті між словами залишається один пробіл.
    """
    words = s.split()
    return " ".join(reversed(words))